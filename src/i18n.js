/** Traduz uma chave, preenchendo {parâmetros} e nomes de teclas ({jump}, {tide}…). */
export function t(key, params = {}) {
  const table = TABLES[lang];
  let s = table[key] ?? pt[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => {
    if (k in params) return params[k];
    const kk = (usingPad ? 'pad.' : 'key.') + k;
    return table[kk] ?? m;
  });
}

export const LANGUAGES = [['pt-BR', 'Português (Brasil)'], ['en', 'English']];
